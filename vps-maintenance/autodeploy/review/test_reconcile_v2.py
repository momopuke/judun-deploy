import importlib.util
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

p = Path(__file__).with_name('reconcile_v2.py')
spec = importlib.util.spec_from_file_location('sc_reconcile_v2', p)
r = importlib.util.module_from_spec(spec)
spec.loader.exec_module(r)

class UnitEquivalence(unittest.TestCase):
    def setUp(self):
        self.service = Path('/etc/systemd/system/sc-vps-autodeploy.service')
        self.timer = Path('/etc/systemd/system/sc-vps-autodeploy.timer')

    def test_identical_known_service(self):
        self.assertIsNone(r.ensure_known_unit(self.service, r.UNIT_SERVICE.encode(), {r.UNIT_SERVICE.encode()}))

    def test_only_comments_different(self):
        raw = ('; unit generated by trusted installer\n' + r.UNIT_SERVICE + '\n# Another comment\n').encode()
        self.assertIsNone(r.ensure_known_unit(self.service, raw, {r.UNIT_SERVICE.encode()}))

    def test_whitespace_and_crlf_only(self):
        s = r.UNIT_SERVICE.replace('Type=oneshot', ' Type = oneshot ')
        s = s.replace('\n', '\r\n')
        self.assertIsNone(r.ensure_known_unit(self.service, s.encode(), {r.UNIT_SERVICE.encode()}))

    def test_unknown_execstart_is_blocked_and_redacted(self):
        raw = r.UNIT_SERVICE.replace('ExecStart=/usr/bin/python3 /opt/sc-vps-autodeploy/pull_agent.py',
                                     'ExecStart=/bin/sh -c secret=value')
        with patch('builtins.print') as out:
            with self.assertRaisesRegex(r.Stop, 'UNKNOWN_UNIT_CONTENTS'):
                r.ensure_known_unit(self.service, raw.encode(), {r.UNIT_SERVICE.encode()})
        log = '\n'.join(map(str, out.call_args_list))
        self.assertNotIn('secret=value', log)
        self.assertIn('SC_VPS_UNKNOWN_UNIT_FINGERPRINT', log)

    def test_unknown_environment_is_blocked_and_redacted(self):
        raw = r.UNIT_SERVICE + '\nEnvironment=MY_SECRET=TOPSECRET\n'
        with patch('builtins.print') as out:
            with self.assertRaises(r.Stop):
                r.ensure_known_unit(self.service, raw.encode(), {r.UNIT_SERVICE.encode()})
        log = str(out.call_args_list)
        self.assertNotIn('TOPSECRET', log)
        self.assertNotIn('MY_SECRET', log)

    def test_timeout_difference_is_blocked_with_safe_hint(self):
        raw = r.UNIT_SERVICE.replace('TimeoutStartSec=900s','TimeoutStartSec=260s')
        report = r.unit_diagnostic(self.service, raw.encode(), {r.UNIT_SERVICE.encode()})
        self.assertEqual(report['safe_timing_limits']['TimeoutStartSec'],'260s')
        self.assertEqual(report['changed_safe_setting_keys'],['TimeoutStartSec'])
        with patch('builtins.print'):
            with self.assertRaises(r.Stop):
                r.ensure_known_unit(self.service,raw.encode(), {r.UNIT_SERVICE.encode()})

    def test_symlink_check_preserved(self):
        with tempfile.TemporaryDirectory() as td:
            t = Path(td); (t/'a').write_text('hello');(t/'b').symlink_to(t/'a')
            with self.assertRaisesRegex(r.Stop,'SYMLINK_NOT_ALLOWED'):
                r.safe_read(t/'b')

    def test_timer_180_and_300_both_accepted(self):
        values = {r.UNIT_TIMER_180.encode(),r.UNIT_TIMER_300.encode()}
        for t in values:
            self.assertIsNone(r.ensure_known_unit(self.timer,t,values))
            self.assertIsNone(r.ensure_known_unit(self.timer,b'# comment\n'+t,values))

    def test_unparseable_unit_does_not_leak(self):
        blob = b'[Service]\nExecStart=\\secret\\do\\not\\log\n'
        with patch('builtins.print') as out:
            with self.assertRaises(r.Stop):
                r.ensure_known_unit(self.service,blob,{r.UNIT_SERVICE.encode()})
        self.assertNotIn('secret', str(out.call_args_list))

    def test_new_first_run_still_status_only(self):
        self.assertEqual(r.decide(True,True,True,True,'MISSING',False,False),'FIRST_STATUS')
        self.assertEqual(r.valid_state(b'{"last_sequence":1,"operation":"apply","status":"applied"}'),'UNRESOLVED')

if __name__ == '__main__': unittest.main()
